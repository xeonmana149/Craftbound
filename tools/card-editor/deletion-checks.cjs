"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path");
const M=require("./model.js");
const base=JSON.parse(fs.readFileSync(path.join(__dirname,"../../src/test/resources/craftbound/test-cards.json"),"utf8"));
const draft=M.clone(base),id="craftbound:ravager",numbers=draft.cards.filter(c=>!c.token).map(c=>c.id);
M.deleteCard(draft,id,base);
assert.equal(draft.cards.find(c=>c.id===id).deleted,true);
assert.deepEqual(draft.cards.filter(c=>!c.token).map(c=>c.id),numbers);
assert.deepEqual(M.validate(draft,base),[]);
delete draft.cards.find(c=>c.id===id).deleted;
assert.deepEqual(M.validate(draft,base),[]);
const fresh={...M.clone(draft.cards.find(c=>c.id===id)),id:"craftbound:test_new_card"};
draft.cards.push(fresh);M.deleteCard(draft,fresh.id,base);
assert.ok(!draft.cards.includes(fresh));
assert.throws(()=>M.deleteCard(draft,"craftbound:wolf_pup",base),/Required by/);
assert.throws(()=>M.deleteCard(draft,"craftbound:vex",base),/Used by/);
const source=draft.cards.find(c=>c.id===id);
source.effects.push({...M.effect(),action:"GIVE_RANDOM",target:"SELF",excludeSelf:false,pool:["craftbound:skeleton"]});
assert.throws(()=>M.deleteCard(draft,"craftbound:skeleton",base),/Used by/);
source.effects=[];source.deleted=true;
assert.equal(M.xpCurve(draft.cards,"NEUTRAL").total,M.xpCurve(base.cards,"NEUTRAL").total-1);
const broken=M.clone(base);broken.cards.find(c=>c.id==="craftbound:vex").deleted=true;
assert.ok(M.validate(broken,base).some(e=>e.includes("Referenced card is deleted")));
const last=M.clone(base);last.cards.forEach(c=>{if(c.rarity==="LEGENDARY")c.deleted=true});
const legendary=last.cards.find(c=>c.rarity==="LEGENDARY"&&!c.token);delete legendary.deleted;
assert.doesNotThrow(()=>M.deleteCard(last,legendary.id,base));
console.log("PASS: saved-card deletion and restoration preserve IDs; draft deletion, reference guards, core tokens, rarity pools and XP curves.");
