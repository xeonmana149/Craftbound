const assert=require('node:assert/strict'),fs=require('node:fs'),M=require('./model.js');
const source=JSON.parse(fs.readFileSync('src/test/resources/craftbound/test-cards.json','utf8'));
const data=M.clone(source);
const wall=data.cards.find(x=>x.keywords.includes('BLOCK')&&!x.deleted);
const flint=data.cards.find(x=>x.kind==='ITEM'&&!x.deleted&&!x.token);
flint.autoText=true;flint.element='FIRE';
const burn={...M.effect(),trigger:'PLAY',action:'DAMAGE',target:'ENEMY_MOBS',boardKind:'BOTH',type:'',amount:3,excludeSelf:false,card:'',boost:{when:'YOU_CONTROL',card:wall.id,type:'',kind:'BOTH',how:'DOUBLE'}};
flint.effects=[burn];
assert.deepEqual(M.validate(data,source),[],'Flint with a Netherrack boost is valid');
const text=M.description(flint,data);
assert.ok(!text.startsWith('Fire.'),'An action shows its element on the type label, not in the text: '+text);
const mobCard=M.clone(data.cards.find(x=>x.kind==='MOB'&&!x.keywords.includes('BLOCK')&&!x.deleted));mobCard.autoText=true;mobCard.element='ENDER';
assert.ok(M.description(mobCard,data).startsWith('Ender. '),'Other kinds print the element first');
assert.ok(text.includes('(doubled if you control '+wall.name+')'),'Boost wording: '+text);
assert.equal(M.boostText({when:'TARGET_IS',kind:'MOB',type:'UNDEAD',how:'PLUS',amount:2},data),' (+2 against Undead mobs)');
assert.equal(M.boostText({when:'ENEMY_CONTROLS',kind:'BLOCK',type:'',how:'TRIPLE'},data),' (tripled if an enemy controls a block)');
assert.equal(M.boostText({when:'ANYONE_CONTROLS',kind:'BOTH',type:'UNDEAD',how:'DOUBLE'},data),' (doubled if an Undead mob or block is in play)');
assert.equal(M.boostText({when:'TARGET_FROZEN',how:'TRIPLE'},data),' (tripled against Frozen targets)');
wall.autoText=true;wall.passive='AMPLIFY_ELEMENT';wall.passiveAmount=0;wall.ampElement='FIRE';wall.ampHow='DOUBLE';
assert.deepEqual(M.validate(data,source),[],'Amplify passive is valid');
assert.ok(M.description(wall,data).includes('Your Fire effects deal double damage.'),'Amplify wording');
wall.ampHow='PLUS';wall.passiveAmount=2;assert.ok(M.description(wall,data).includes('Your Fire effects deal +2 damage.'),'Amplify plus wording');
burn.boost={when:'TARGET_FROZEN',how:'DOUBLE'};flint.effects=[{...burn,action:'DRAW',target:'SELF'}];
assert.ok(M.validate(data,source).some(e=>String(e).includes('Target conditions')),'Draw cannot use target conditions');
flint.effects=[{...burn,action:'GIVE',target:'SELF',card:wall.id,boost:{when:'YOU_CONTROL',kind:'BOTH',how:'DOUBLE'}}];
assert.ok(M.validate(data,source).some(e=>String(e).includes('Boosts work on')),'Boosts only on number effects');
console.log('PASS: elements, boost wording and validation, and Amplify element.');
